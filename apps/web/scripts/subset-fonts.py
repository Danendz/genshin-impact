"""Split the full HYWenHei-HEW woff2 into unicode-range subsets.

Run (source font from `git show legacy:public/fonts/genshin-text/HYWenHei-HEW.woff2`):

  uvx --from "fonttools[woff]" --with jieba python scripts/subset-fonts.py <HYWenHei-HEW.woff2>

Outputs src/assets/fonts/hywenhei/*.woff2 and src/styles/fonts.css.

CJK ordering (simple, offline): characters are ranked by
  1. GB2312 level 1 (the ~3755 common simplified chars), by frequency summed
     over jieba's bundled word-frequency dictionary;
  2. Big5 "frequently used" block A440-C67E (~5400 common traditional chars),
     in Big5 order;
  3. the rest of GB2312 / Big5 (level 2 / rare);
  4. every other U+4E00-9FFF glyph in the font, by code point.
Ranked characters are cut into chunks of CHUNK code points, so common text
touches few chunks. CJK/fullwidth punctuation (U+3000-303F, U+FF00-FFEF) gets
its own chunk.
"""

import os
import sys
from collections import Counter

import jieba
from fontTools import subset
from fontTools.ttLib import TTFont

CHUNK = 300
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src/assets/fonts/hywenhei")
CSS = os.path.join(ROOT, "src/styles/fonts.css")

LATIN_CYRILLIC = (
    list(range(0x0000, 0x0250))
    + list(range(0x0400, 0x0500))
    + list(range(0x2000, 0x2070))
    + [0x20AC]
)
PUNCT = list(range(0x3000, 0x3040)) + list(range(0xFF00, 0xFFF0))


def han_codes(codec, hi_lo):
    """Han characters of a legacy double-byte codec, in codec order."""
    out = []
    for hi in range(hi_lo[0], hi_lo[1] + 1):
        for lo in range(0x40, 0xFF):
            try:
                ch = bytes([hi, lo]).decode(codec)
            except UnicodeDecodeError:
                continue
            if len(ch) == 1 and 0x4E00 <= ord(ch) <= 0x9FFF:
                out.append(ord(ch))
    return out


def char_freq():
    freq = Counter()
    path = os.path.join(os.path.dirname(jieba.__file__), "dict.txt")
    with open(path, encoding="utf-8") as f:
        for line in f:
            word, n, *_ = line.split()
            for ch in word:
                freq[ord(ch)] += int(n)
    return freq


def ranked_han(available):
    freq = char_freq()
    gb1 = han_codes("gb2312", (0xB0, 0xD7))
    gb2 = han_codes("gb2312", (0xD8, 0xF7))
    big5_common = han_codes("big5", (0xA4, 0xC6))
    big5_rare = han_codes("big5", (0xC9, 0xF9))
    order = sorted(gb1, key=lambda c: -freq[c])
    seen = set()
    ranked = []
    for group in (order, big5_common, gb2, big5_rare, sorted(available)):
        for c in group:
            if c in available and c not in seen and 0x4E00 <= c <= 0x9FFF:
                seen.add(c)
                ranked.append(c)
    return ranked


def ranges(codes):
    codes = sorted(codes)
    parts, start, prev = [], codes[0], codes[0]
    for c in codes[1:] + [None]:
        if c is not None and c == prev + 1:
            prev = c
            continue
        parts.append(f"U+{start:04X}" if start == prev else f"U+{start:04X}-{prev:04X}")
        if c is not None:
            start = prev = c
    return ", ".join(parts)


def write_subset(src, codes, name):
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.notdef_outline = True
    font = TTFont(src)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=codes)
    sub.subset(font)
    path = os.path.join(OUT, name)
    font.flavor = "woff2"
    font.save(path)
    return os.path.getsize(path)


def main(src):
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        os.remove(os.path.join(OUT, f))
    available = set(TTFont(src).getBestCmap())
    faces = []  # (label, filename, codes)
    faces.append(("latin-cyrillic", "latin-cyrillic.woff2", [c for c in LATIN_CYRILLIC if c in available]))
    # Declare the full requested ranges (the font has gaps inside them); the
    # browser just falls back for glyphs the file lacks.
    declared = {"latin-cyrillic": "U+0000-024F, U+0400-04FF, U+2000-206F, U+20AC"}
    faces.append(("cjk-punct", "cjk-punct.woff2", [c for c in PUNCT if c in available]))
    han = ranked_han(available)
    for i in range(0, len(han), CHUNK):
        n = i // CHUNK + 1
        faces.append((f"cjk-{n:02d}", f"cjk-{n:02d}.woff2", han[i : i + CHUNK]))

    css = ["/* Generated by scripts/subset-fonts.py. Do not edit. */"]
    for label, fname, codes in faces:
        size = write_subset(src, codes, fname)
        print(f"{fname}: {len(codes)} cps, {size // 1024} KB")
        css.append(
            f"@font-face {{\n  /* {label} */\n  font-family: \"HYWenHei\";\n  font-style: normal;\n"
            f"  font-weight: 400;\n  font-display: swap;\n"
            f"  src: url(\"../assets/fonts/hywenhei/{fname}\") format(\"woff2\");\n"
            f"  unicode-range: {declared.get(label) or ranges(codes)};\n}}"
        )
    css.append(
        "@font-face {\n  font-family: \"GenshinIcon\";\n  font-style: normal;\n  font-weight: 400;\n"
        "  font-display: block;\n  src: url(\"../assets/fonts/genshinicon.woff2\") format(\"woff2\");\n}"
    )
    with open(CSS, "w", encoding="utf-8") as f:
        f.write("\n".join(css) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
