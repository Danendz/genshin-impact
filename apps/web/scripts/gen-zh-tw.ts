// Generates src/i18n/strings.zh-TW.ts from the zh-CN dictionary with OpenCC (cn -> tw).
// Run: pnpm --filter @gi/web i18n:zh-tw, then review the output by hand.
import { writeFileSync } from 'node:fs'
import * as OpenCC from 'opencc-js'
import { zhCN } from '../src/i18n/strings.zh-CN.ts'

const toTW = OpenCC.Converter({ from: 'cn', to: 'tw' })
const body = Object.entries(zhCN)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(toTW(v))},`)
  .join('\n')
writeFileSync(
  new URL('../src/i18n/strings.zh-TW.ts', import.meta.url),
  `// Generated by scripts/gen-zh-tw.ts from strings.zh-CN.ts; edit zh-CN and regenerate.\nimport type { Dictionary } from './strings.zh-CN'\n\nexport const zhTW: Dictionary = {\n${body}\n}\n`,
)
